const assert=require('node:assert/strict');
const {criarServidor}=require('../integracao/servidor.cjs');
module.exports=async function(browser){
 const {servidor}=criarServidor();await new Promise(r=>servidor.listen(0,'127.0.0.1',r));
 const base='http://127.0.0.1:'+servidor.address().port;
 const contexto=await browser.newContext();const p=await contexto.newPage();
 let pronto=false,buscas=0,atualizando=false;
 try{
  await p.route('**/api/fontes',r=>r.fulfill({json:{desktop:true,fontes:[{id:'teste',nome:'Teste'}]}}));
  await p.route('**/api/indice?*',r=>r.fulfill({json:pronto?{fase:atualizando?'verificando':'pronto',pronto:true,total:200,processados:200,atualizadoEm:new Date().toISOString()}:{fase:'verificando',total:200,processados:75,pronto:false}}));
  await p.route('**/api/notas?*',r=>{buscas++;return r.fulfill({status:pronto?200:202,json:pronto?{notas:[],erros:[],total:0}:{preparando:true,indice:{fase:'verificando',total:200,processados:75,pronto:false}}})});
  await p.goto(base);
  await p.waitForFunction(()=>document.querySelector('#barraBusca').value===75);
  assert.equal(await p.locator('#btnIntegracao').textContent(),'Buscar nas pastas');
  assert.equal(await p.locator('#filtrosBusca').getAttribute('open'),null);
  assert.equal(await p.locator('#barraBusca').getAttribute('max'),'200');
  assert.match(await p.locator('#textoProgressoBusca').textContent(),/75 de 200/);
  assert.equal(await p.locator('#btnBuscarIntegracao').getAttribute('aria-label'),'Buscar nota');
  await p.locator('#buscaIntegracao').fill('764');await p.locator('#buscaIntegracao').press('Enter');
  await p.waitForFunction(()=>document.querySelector('#statusIntegracao').textContent.includes('preparação terminar'));
  assert.equal(buscas,1);
  assert.equal(await p.locator('#indicadorIntegracao').getAttribute('data-estado'),'amarelo');
  await p.locator('#ajudaEstadoIntegracao').hover();
  assert.equal(await p.locator('#descricaoEstadoIntegracao').isVisible(),true);
  assert.match(await p.locator('#descricaoEstadoIntegracao').textContent(),/Preparando/);
  pronto=true;
  await p.waitForFunction(()=>document.querySelector('#statusIntegracao').textContent.includes('0 resultado'));
  assert.equal(buscas,2);
  assert.equal(await p.locator('#indicadorIntegracao').getAttribute('data-estado'),'verde');
  await p.locator('#ajudaEstadoIntegracao').focus();
  assert.equal(await p.locator('#descricaoEstadoIntegracao').isVisible(),true);
  await p.locator('#ajudaEstadoIntegracao').press('Escape');
  await p.mouse.move(0,0);
  assert.equal(await p.locator('#descricaoEstadoIntegracao').isVisible(),false);
  await p.locator('#ajudaEstadoIntegracao').click();
  assert.equal(await p.locator('#ajudaEstadoIntegracao').getAttribute('aria-expanded'),'true');
  assert.equal(await p.locator('#progressoBusca').isVisible(),false);
  assert.equal(await p.locator('#buscaAutomatica').isChecked(),false);
  atualizando=true;
  await p.waitForFunction(()=>document.querySelector('#descricaoEstadoIntegracao').textContent.includes('segundo plano'));
  assert.equal(await p.locator('#progressoBusca').isVisible(),false);
  assert.equal(buscas,2);
  atualizando=false;
  await p.setViewportSize({width:390,height:844});
  assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.equal(await p.locator('#btnBuscarIntegracao').isVisible(),true);
  await p.route('**/api/fontes',r=>r.abort());
  await p.reload();
  await p.waitForFunction(()=>document.querySelector('#indicadorIntegracao').dataset.estado==='vermelho');
  console.log('Busca: lupa, Enter, filtros recolhidos, progresso real, busca aguardando índice e mobile verificados.');
 }finally{await contexto.close();await new Promise(r=>servidor.close(r))}
};