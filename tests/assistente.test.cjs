const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { diagnosticar } = require('../desktop/diagnostico.cjs');
const { xmlNota } = require('./ajudantes.cjs');
const { criarServidor } = require('../integracao/servidor.cjs');
test('diagnóstico distingue pasta vazia, XML inválido, notas válidas e pasta ausente sem modificar XML', async t => {
  const raiz = await fs.mkdtemp(path.join(os.tmpdir(), 'etiquetas-assistente-'));
  t.after(() => fs.rm(raiz, {recursive:true,force:true}));
  const pastas = ['vazia','invalida','valida'].map(p=>path.join(raiz,p));
  await Promise.all(pastas.map(p=>fs.mkdir(p)));
  await fs.writeFile(path.join(pastas[1],'nota.xml'),'<invalido>');
  const xml = xmlNota();
  await fs.writeFile(path.join(pastas[2],'nota.xml'),xml);
  const resultados=await diagnosticar([...pastas,path.join(raiz,'ausente')]);
  assert.deepEqual(resultados.map(r=>r.estado), ['vazia','xml-invalido','pronta','inexistente']);
  assert.equal(resultados[2].notas,1);
  assert.equal(await fs.readFile(path.join(pastas[2],'nota.xml'),'utf8'),xml);
});
test('assistente aceita apenas sessão local e controle do iniciador exige segredo', async t => {
  const { servidor,token }=criarServidor({}, {desktop:true});
  await new Promise(r=>servidor.listen(0,'127.0.0.1',r));
  t.after(()=>new Promise(r=>servidor.close(r)));
  const base=`http://127.0.0.1:${servidor.address().port}`;
  const headers={Authorization:`Bearer ${token}`};
  assert.equal((await fetch(base+'/api/diagnostico')).status,401);
  assert.deepEqual(await(await fetch(base+'/api/diagnostico',{headers})).json(),{pastas:[]});
  assert.equal((await fetch(base+'/api/assistente',{method:'POST'})).status,401);
  assert.equal((await fetch(base+'/api/assistente',{method:'POST',headers:{...headers,Origin:'https://externo.example'}})).status,403);
  const {caminho}=await(await fetch(base+'/api/sessao',{method:'POST',headers})).json();
  const sessao=await fetch(base+caminho,{redirect:'manual'});
  const cookie=sessao.headers.get('set-cookie').split(';')[0];
  assert.equal((await fetch(base+'/api/assistente',{method:'POST',headers:{Cookie:cookie}})).status,202);
  assert.equal((await fetch(base+'/api/controle',{headers:{Cookie:cookie}})).status,401);
  assert.deepEqual(await(await fetch(base+'/api/controle',{headers})).json(),{abrirAssistente:true});
  assert.deepEqual(await(await fetch(base+'/api/controle',{headers})).json(),{abrirAssistente:false});
  assert.equal((await fetch(base+'/api/assistente?comando=outro',{method:'GET',headers})).status,400);
});
