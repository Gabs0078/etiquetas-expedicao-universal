'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),files=['messages.json','runtime.json','native.json','guide.json'];
function catalog(){
 const out={};
 for(const name of files)for(const row of JSON.parse(fs.readFileSync(path.join(root,'assets/i18n',name),'utf8'))){
  if(row.length!==4||row.some(x=>typeof x!=='string'||!x))throw Error('Incomplete translation: '+row[0]);
  if(out[row[0]])throw Error('Duplicate translation: '+row[0]);
  const tokens=s=>(s.match(/\{\d+\}/g)||[]).sort().join(',');
  if(row.some(x=>tokens(x)!==tokens(row[0])))throw Error('Mismatched placeholders: '+row[0]);
  out[row[0]]=row;
 }
 return out;
}
function generated(){const rows=catalog();return {'catalogs.json':JSON.stringify(Object.values(rows))+'\n','catalogs.js':'/* Generated by scripts/compilar-i18n.cjs. Edit the JSON catalogs. */\nglobalThis.TagEXMessages='+JSON.stringify(rows)+';\n'};}
if(require.main===module)for(const [name,content]of Object.entries(generated()))fs.writeFileSync(path.join(root,'assets/i18n',name),content);
module.exports={catalog,generated};
